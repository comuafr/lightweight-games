#!/usr/bin/env python3
"""Generates the embedded Hangman word lists (Kotlin) from the curated text files in this folder.

Source: tools/wordlist/fr.txt and en.txt are hand-curated lists of concrete, kid-friendly nouns
written for this project (no external corpus, no license constraint). Rules applied here:
5 to 9 letters, lowercase a-z only (no accents, so the on-screen keyboard stays 26 keys),
deduplicated, sorted, and emitted as a Kotlin `internal object` with a `WORDS: Array<String>`.

Usage: tools/wordlist/build_wordlist.py   (rewrites core/src/commonMain/kotlin/lg/core/games/hangman/Words*.kt)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "core", "src", "commonMain", "kotlin", "lg", "core", "games", "hangman")
WORD_RE = re.compile(r"^[a-z]{5,9}$")


def load(name):
    words = set()
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            for w in line.split():
                w = w.strip().lower()
                if WORD_RE.match(w):
                    words.add(w)
    return sorted(words)


def emit(lang, obj, words):
    lines = [
        "package lg.core.games.hangman",
        "",
        "// GENERATED by tools/wordlist/build_wordlist.py from tools/wordlist/%s.txt. Do not edit by hand." % lang,
        "// %d words, 5-9 letters, a-z only." % len(words),
        "internal object %s {" % obj,
        "    val WORDS: Array<String> = arrayOf(",
    ]
    row = []
    for w in words:
        row.append('"%s"' % w)
        if len(row) == 8:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    lines += ["    )", "}", ""]
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, "%s.kt" % obj)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d words)" % (os.path.relpath(path), len(words)))


if __name__ == "__main__":
    emit("fr", "WordsFr", load("fr.txt"))
    emit("en", "WordsEn", load("en.txt"))
